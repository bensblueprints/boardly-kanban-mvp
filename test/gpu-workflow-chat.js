const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const express=require('express');
const Database=require('better-sqlite3');
const {createGpuWorkflows}=require('../server/gpu-workflows');
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));

(async()=>{
  const db=new Database(':memory:');db.pragma('foreign_keys=ON');
  let answer,gate,resolveGate,aiCalls=0,renders=0,retained=0,lastPayload;
  const ssh={forService:()=>({id:'ssh'}),list:()=>[]};
  const remote=async(w,p)=>{
    if(p.action==='snapshot')return {gpus:[{uuid:'gpu-one'}],engines:[{port:8188,online:true}],jobs:[]};
    renders++;return {status:'submitted'};
  };
  const generate=async(actor,id,payload)=>{
    assert.equal(actor,'owner');assert.equal(gpu.live(actor,id),true,'Conversation turns authorize the existing subscription bridge');
    assert.equal(gpu.live('someone-else',id),false);assert.deepEqual(payload.tools,[]);
    aiCalls++;lastPayload=payload;
    if(gate)await gate;
    return {output_text:typeof answer==='string'?answer:JSON.stringify(answer)};
  };
  const make=()=>createGpuWorkflows({db,ssh,ownerId:'owner',generate,remote,actions:()=>({projects:()=>[{id:7,name:'Client project'}]}),retain:()=>retained++,release:()=>retained--,interval:3600000});
  let gpu=make();
  const app=express();app.use((req,res,next)=>{req.workspaceIsOwner=req.headers['x-owner']==='yes';next();});
  app.use((req,res,next)=>gpu.router(req,res,next));app.use((e,req,res,next)=>res.status(e.status||500).json({error:e.message}));
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const request=async(path,body,method='POST',owner=true)=>{
    const response=await fetch('http://127.0.0.1:'+server.address().port+'/api/gpu'+path,{method,headers:{'content-type':'application/json','x-owner':owner?'yes':'no'},body:body===undefined?undefined:JSON.stringify(body)});
    return {status:response.status,data:await response.json()};
  };
  const read=async id=>(await request('/workflow-chats/'+id,undefined,'GET')).data;
  const done=async id=>{for(let i=0;i<100;i++){const c=await read(id);if(!c.turns.some(t=>['queued','running'].includes(t.status)))return c;await wait(5);}throw Error('Reply did not finish');};
  const say=async(c,content='Build an image and caption workflow')=>request('/workflow-chats/'+c.id+'/messages',{version:c.version,client_id:crypto.randomUUID(),content});
  try {
    assert.equal((await request('/workflow-chats',undefined,'GET')).status,409);
    assert.equal((await request('/workflow-chats',undefined,'GET',false)).status,403);
    const w=await gpu.addWorker({name:'Test GPU',ssh_id:'ssh',ports:[8188]});
    const t=gpu.addTemplate({name:'Available image template',worker_id:w.id,kind:'image',port:8188,graph:{'1':{class_type:'Text',inputs:{text:'{{prompt}}'}}}});
    const video=gpu.addTemplate({name:'Animate previous image',worker_id:w.id,kind:'video',port:8188,graph:{'1':{class_type:'Video',inputs:{text:'{{prompt}}',image:'{{previous_file}}'}}}});
    const videoStep={kind:'video',template_id:video.id,prompt:'Animate {{prompt}}'};
    assert.equal((await request('/workflows',{name:'Missing source image',steps:[videoStep]})).status,400);
    assert.equal((await request('/workflows',{name:'Image to video',steps:[{kind:'image',template_id:t.id,prompt:'{{prompt}}'},videoStep]})).status,201);
    db.prepare('DELETE FROM gpu_workflows').run();
    let c=(await request('/workflow-chats',{request_id:crypto.randomUUID()})).data;
    const draft={name:'Image and caption',steps:[{kind:'image',template_id:t.id,prompt:'Create {{prompt}}'},{kind:'prompt',prompt:'Caption the idea {{prompt}}'}]};
    answer={reply:'Here is an image workflow followed by a caption.',draft,suggestions:['Add project delivery']};
    const body={version:c.version,client_id:crypto.randomUUID(),content:'Build an image and caption workflow'};
    await request('/workflow-chats/'+c.id+'/messages',body);
    c=await done(c.id);assert.equal(c.turns[0].status,'completed');assert.deepEqual(c.draft,draft);
    assert.match(JSON.stringify(lastPayload),/Available image template/);
    assert.equal(gpu.workflows().length,0);assert.equal(renders,0,'A reply does not save or execute');
    await request('/workflow-chats/'+c.id+'/messages',body);assert.equal(aiCalls,1,'Message retries do not rebill');
    assert.equal((await request('/workflow-chats/'+c.id+'/messages',{...body,content:'Different'})).status,409);
    const save={version:c.version,request_id:crypto.randomUUID()};
    let result=await request('/workflow-chats/'+c.id+'/apply',save);assert.equal(result.status,200);
    const wf=result.data.workflow;c=result.data.chat;
    await request('/workflow-chats/'+c.id+'/apply',save);assert.equal(gpu.workflows().length,1,'Save retries do not duplicate');
    assert.equal(renders,0,'Saving does not execute');
    assert.equal(db.prepare('SELECT COUNT(*) n FROM gpu_workflow_runs').get().n,0);
    answer={reply:'I added a project action.',draft:{...draft,steps:[...draft.steps,{kind:'action',project_id:7,prompt:'Save the generated output to this project.'}]}};
    await say(c,'Add project delivery');c=await done(c.id);assert.equal(c.draft.steps.length,3);
    assert.equal(gpu.workflows()[0].steps.length,2,'Edits stay in the draft until saved');
    result=await request('/workflow-chats/'+c.id+'/apply',{version:c.version,request_id:crypto.randomUUID()});c=result.data.chat;
    assert.equal(result.data.workflow.id,wf.id);assert.equal(result.data.workflow.steps.length,3);
    const before=c.draft;
    answer={reply:'This template does not exist.',draft:{name:'Invalid',steps:[{kind:'video',template_id:crypto.randomUUID(),prompt:'x'}]}};
    await say(c);c=await done(c.id);assert.equal(c.turns.at(-1).status,'failed');assert.deepEqual(c.draft,before);
    answer='not JSON';await request('/workflow-chats/'+c.id+'/retry',{version:c.version,turn_id:c.turns.at(-1).id});c=await done(c.id);assert.equal(c.turns.at(-1).status,'failed');
    answer={reply:'Which project should receive the output?',draft:null};await request('/workflow-chats/'+c.id+'/retry',{version:c.version,turn_id:c.turns.at(-1).id});c=await done(c.id);assert.equal(c.turns.at(-1).status,'completed');assert.deepEqual(c.draft,before);
    gpu.saveWorkflow({name:'Changed in another tab',steps:draft.steps},wf.id);
    result=await request('/workflow-chats/'+c.id+'/apply',{version:c.version,request_id:crypto.randomUUID()});assert.equal(result.status,409);
    assert.equal(gpu.workflows()[0].name,'Changed in another tab');
    result=await request('/workflow-chats/'+c.id+'/apply',{version:c.version,request_id:crypto.randomUUID(),as_new:true});assert.equal(result.status,200);c=result.data.chat;assert.notEqual(c.workflow_id,wf.id);assert.equal(gpu.workflows().length,2);
    const editing=(await request('/workflow-chats',{request_id:crypto.randomUUID(),workflow_id:wf.id})).data;
    assert.equal(editing.draft.name,'Changed in another tab');
    assert.equal((await request('/workflow-chats',{request_id:crypto.randomUUID(),workflow_id:crypto.randomUUID()})).status,404);
    gate=new Promise(resolve=>resolveGate=resolve);
    answer={reply:'A draft',draft};await say(editing);await wait(5);
    assert.equal((await say(editing,'Concurrent')).status,409);
    assert.equal((await request('/workflow-chats/'+editing.id+'/apply',{version:editing.version,request_id:crypto.randomUUID()})).status,409);
    const previous=gpu;previous.close();gpu=make();let recovered=await read(editing.id);assert.equal(recovered.turns.at(-1).status,'failed');assert.match(recovered.turns.at(-1).error,/restarted/);
    resolveGate();gate=null;await wait(20);assert.equal((await read(editing.id)).turns.at(-1).status,'failed','Late previous-process results do not alter recovered state');
    await request('/workflow-chats/'+editing.id+'/retry',{version:recovered.version,turn_id:recovered.turns.at(-1).id});recovered=await done(editing.id);assert.equal(recovered.turns.at(-1).status,'completed');
    assert.equal((await request('/workflow-chats/'+c.id,undefined,'GET',false)).status,403);
    assert.equal((await request('/workflow-chats/'+c.id+'/apply',{version:c.version,request_id:crypto.randomUUID()},'POST',false)).status,403);
    assert.equal(renders,0);assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
    console.log('PASS GPU workflow chat: create/edit, valid resource grounding, no render/action side effects, owner access, idempotent messages/saves, conflict protection, failed reply retry and restart recovery');
  } finally {gpu.close();await wait(10);await new Promise(r=>server.close(r));assert.equal(retained,0);db.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
